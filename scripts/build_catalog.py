#!/usr/bin/env python3
"""Regenerate CATALOG.md, catalog.json and llms.txt from the skills on disk.

Usage:  python3 scripts/build_catalog.py

Run after adding or changing any skill's frontmatter. The generated files are
committed so that tools without a script runner can still route by them.
"""

from __future__ import annotations

import json
from collections import defaultdict

from skilllib import CATEGORIES, ROOT, load_all

REPO_TITLE = "Universal LLM Skills"


def main() -> None:
    skills = load_all()
    by_cat = defaultdict(list)
    for s in skills:
        by_cat[s.category].append(s)

    # catalog.json — machine-readable index for routers and tools.
    catalog = {
        "name": REPO_TITLE,
        "description": "Deep, style-neutral skills for any LLM across development, analysis, design, quality, automation and more.",
        "entry_point": "AGENTS.md",
        "skill_count": len(skills),
        "categories": {k: v for k, v in CATEGORIES.items() if by_cat.get(k)},
        "skills": [
            {
                "name": s.name,
                "category": s.category,
                "description": s.description,
                "path": s.rel_path,
                "references": s.references,
                "related": s.related,
            }
            for s in skills
        ],
    }
    (ROOT / "catalog.json").write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    # CATALOG.md — human- and LLM-readable index.
    md = [
        "# Skill Catalog",
        "",
        "<!-- Generated by scripts/build_catalog.py. Do not edit by hand. -->",
        "",
        f"{len(skills)} skills. Pick a primary skill by matching the deliverable to a description, "
        "then add supporting skills sparingly. See [`AGENTS.md`](AGENTS.md) and "
        "[`skills/using-skills`](skills/using-skills/SKILL.md) for how to route.",
        "",
        "## Categories",
        "",
    ]
    for key, title in CATEGORIES.items():
        if by_cat.get(key):
            anchor = title.lower().replace(",", "").replace(":", "").replace(" ", "-")
            md.append(f"- [{title}](#{anchor}) — {len(by_cat[key])} skills")
    md.append("")
    for key, title in CATEGORIES.items():
        if not by_cat.get(key):
            continue
        md += [f"## {title}", "", "| Skill | Use it for |", "|---|---|"]
        for s in by_cat[key]:
            desc = s.description.replace("|", "\\|")
            md.append(f"| [`{s.name}`]({s.rel_path}) | {desc} |")
        md.append("")
    (ROOT / "CATALOG.md").write_text("\n".join(md), encoding="utf-8")

    # llms.txt — the llmstxt.org convention, for tools that look for it.
    txt = [
        f"# {REPO_TITLE}",
        "",
        "> A library of deep, style-neutral skills (expert playbooks) that any LLM can load on demand. "
        "Start with AGENTS.md, choose skills from CATALOG.md, then read skills/<name>/SKILL.md.",
        "",
        "## Start here",
        "",
        "- [AGENTS.md](AGENTS.md): how an LLM should use this library",
        "- [CATALOG.md](CATALOG.md): every skill with when-to-use descriptions",
        "- [Skill standard](docs/SKILL_STANDARD.md): format and quality bar",
        "",
    ]
    for key, title in CATEGORIES.items():
        if not by_cat.get(key):
            continue
        txt += [f"## {title}", ""]
        for s in by_cat[key]:
            first = s.description.split(". ")[0].rstrip(".")
            txt.append(f"- [{s.name}]({s.rel_path}): {first}")
        txt.append("")
    (ROOT / "llms.txt").write_text("\n".join(txt), encoding="utf-8")

    print(f"Wrote CATALOG.md, catalog.json, llms.txt for {len(skills)} skills")


if __name__ == "__main__":
    main()
